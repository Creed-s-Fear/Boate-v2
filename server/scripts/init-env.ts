/**
 * Creates server/.env with fresh secrets (deposit address seed and database password).
 * Does not print the secrets. Never overwrites an existing .env: the seed controls the
 * funds of every deposit address.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const file = fileURLToPath(new URL('../.env', import.meta.url));
if (existsSync(file)) {
  console.log('server/.env already exists — nothing changed.');
  process.exit(0);
}

const dbPass = randomBytes(18).toString('base64url');
const env = `# Generated by npm run env:init. Do NOT commit. Back up the seed outside the repository.
NODE_ENV=development
PORT=8787
DATABASE_URL=postgres://boate:${dbPass}@127.0.0.1:5433/boate
POSTGRES_PASSWORD=${dbPass}
ALLOWED_ORIGINS=http://127.0.0.1:5173,http://127.0.0.1:5174,http://localhost:5173,http://localhost:5174

SOLANA_CLUSTER=devnet
# SOLANA_RPC_URL=
DEPOSIT_MASTER_SEED=${randomBytes(32).toString('hex')}
FICHAS_PER_SOL=10000
WELCOME_BONUS=0
# house wallet that receives the sweep (npm run sweep)
TREASURY_ADDRESS=
`;
writeFileSync(file, env, { mode: 0o600 });
console.log('server/.env created (devnet).');
